function norm(s) { return s.toLowerCase().replace(/ё/g, 'е'); }

function localAnswer(question) {
  const q = norm(question);
  let best = null, bestScore = 0;
  for (const item of KB) {
    const score = item.keys.reduce((acc, k) => acc + (q.includes(norm(k)) ? 1 : 0), 0);
    if (score > bestScore) { best = item; bestScore = score; }
  }
  if (!best) {
    return {
      answer: 'Пока не знаю точного ответа на этот вопрос. Попробуйте переформулировать или выберите одну из популярных тем ниже. Если вопрос срочный — напишите в учебный отдел через заявку «Вопрос в деканат».',
      action: { label: 'Задать вопрос сотруднику', href: '#/requests/new?type=question' },
      source: 'kb',
    };
  }
  return { answer: best.a, action: best.action || null, source: 'kb', topic: best.q };
}

async function aiAnswer(question, student) {
  const { AI_API_KEY, AI_BASE_URL, AI_MODEL } = process.env;
  if (!AI_API_KEY || !AI_BASE_URL) return null;
  const kbText = KB.map((k) => `### ${k.q}\n${k.a}`).join('\n\n');
  const system = `Ты — дружелюбный помощник учебного отдела в прототипе личного кабинета студента СПбГУ (концепт для конкурса).
Отвечай по-русски, коротко (до 5 предложений), на «вы», по делу. Опирайся ТОЛЬКО на базу знаний ниже.
Если ответа в базе нет — честно скажи об этом и предложи подать заявку «Вопрос в деканат». Не выдумывай сроки и правила.
Контекст студента: ${student.level}, ${student.course} курс, ${student.program}.

${kbText}`;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 15000);
  try {
    const res = await fetch(`${AI_BASE_URL.replace(/\/$/, '')}/chat/completions`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${AI_API_KEY}` },
      body: JSON.stringify({
        model: AI_MODEL || 'gpt-4o-mini',
        messages: [{ role: 'system', content: system }, { role: 'user', content: question.slice(0, 1000) }],
        temperature: 0.2,
      }),
      signal: controller.signal,
    });
    if (!res.ok) return null;
    const data = await res.json();
    const text = data?.choices?.[0]?.message?.content?.trim();
    if (!text) return null;
    const local = localAnswer(question);
    return { answer: text, action: local.action, source: 'ai' };
  } catch {
    return null; // при любой ошибке — тихо откатываемся к базе знаний
  } finally {
    clearTimeout(timer);
  }
}

async function ask(question, student) {
  return (await aiAnswer(question, student)) || localAnswer(question);
}

